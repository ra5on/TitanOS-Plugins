#!/usr/bin/env python3
"""Collect the original notices of every Go module linked into the NetBird client.

Usage: scripts/netbird-notices.py <netbird binary> <output file>

Run once whenever plugins/netbird/packages.lock.json pins a new client. The
module list comes from the build information of the official binary; each
module is fetched through the Go module proxy and checked against the hash
recorded in that binary (and the public checksum database). The result is
committed and pinned by SHA-256 in the lock file, so the plugin build itself
needs no module downloads. Notice texts are copied verbatim; identical texts
are printed once and referenced afterwards.
"""
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

NOTICE = re.compile(r"^(licen[sc]e|copying|copyright|notice|patents)([._-]|$)", re.I)


def run(*args, **kwargs):
    return subprocess.check_output(args, text=True, **kwargs)


def modules(binary):
    """Yield (path, version, h1 sum, original path) of every linked module."""
    lines = run("go", "version", "-m", binary).splitlines()
    go_version = lines[0].rsplit(": ", 1)[1]
    result, last = [], None
    for line in lines[1:]:
        fields = line.split()
        if not fields:
            continue
        if fields[0] == "dep":
            last = [fields[1], fields[2], fields[3] if len(fields) > 3 else "", fields[1]]
            result.append(last)
        elif fields[0] == "=>":
            # A replacement: the code really linked is the replacement module.
            last[0], last[1], last[2] = fields[1], fields[2], fields[3]
    return go_version, result


def main(binary, output):
    go_version, deps = modules(binary)
    texts, lines = {}, []
    with tempfile.TemporaryDirectory() as cache:
        env = dict(os.environ, GOPATH=cache, GOMODCACHE=cache + "/mod", GOFLAGS="-modcacherw", GO111MODULE="on")
        work = Path(cache) / "work"
        work.mkdir()
        goroot = Path(run("go", "env", "GOROOT").strip())
        entries = [("Go standard library", go_version, "", goroot, [goroot / "LICENSE"])]
        for path, version, h1, original in deps:
            info = json.loads(run("go", "mod", "download", "-json", f"{path}@{version}", cwd=work, env=env))
            if h1 and info["Sum"] != h1:
                raise ValueError(f"{path}@{version}: hash differs from the binary")
            directory = Path(info["Dir"])
            files = sorted(p for p in directory.rglob("*") if p.is_file() and NOTICE.match(p.name)
                           and "testdata" not in p.relative_to(directory).parts)
            if not files:
                raise ValueError(f"missing license text for {path}@{version}")
            name = path if path == original else f"{original} (replaced by {path})"
            entries.append((name, version, f"https://proxy.golang.org/{path}/@v/{version}.zip", directory, files))
        lines += ["NetBird client – notices of the Go modules linked into the binary",
                  "=" * 65,
                  "Generated by scripts/netbird-notices.py from the build information of the",
                  "official netbird binary. Texts are copied verbatim from each module; an",
                  "identical text is printed once and referenced afterwards.",
                  "The Go standard library notice is the one of the local toolchain; the",
                  f"binary was built with {go_version}, whose LICENSE file is the same text.", ""]
        for name, version, source, directory, files in entries:
            lines += ["-" * 78, f"{name} {version}"]
            if source:
                lines.append(f"Source: {source}")
            for file in files:
                text = file.read_text(encoding="utf-8", errors="replace")
                digest = hashlib.sha256(text.encode()).hexdigest()
                relative = file.relative_to(directory)
                if digest in texts:
                    lines.append(f"{relative}: same text as {texts[digest]}")
                    continue
                texts[digest] = f"{name} {version} › {relative}"
                lines += ["", f"{relative}:", "", text.rstrip("\n"), ""]
    Path(output).write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main(*sys.argv[1:3])
