#!/usr/bin/env python3
"""Newer upstream releases of the plugins that pin a downloaded binary.

  upstream.py check
      Prints name=<version> for every plugin with a newer stable upstream
      release than its packages.lock.json, and names=<names> (for
      $GITHUB_OUTPUT).

  upstream.py bump <name> <version>
      Pins the release: URL, size and SHA-256 of the archive in
      plugins/<name>/packages.lock.json, the notices in plugins/<name>/licenses.
      The license of the program itself must stay word for word as it was;
      a changed text exits with 3 and changes nothing, the owner looks at it.
      Lists of third-party notices are updated (NetBird's are generated from
      the binary by scripts/netbird-notices.py, which needs Go).

Only Tailscale and NetBird: their plugins hold a pinned official binary.
NVIDIA drivers are prepared on each NAS (TitanOS docs/NVIDIA-LOCAL-BUILD.md),
drivers of the kernel sets follow the kernel, Coral and Intel GPU Tools come
with the image.
"""
import hashlib
import io
import json
import os
import re
import subprocess
import sys
import tarfile
import tempfile
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
VERSION = re.compile(r"[0-9]+\.[0-9]+\.[0-9]+")
LIMIT = 256 << 20


def get(url, limit=LIMIT):
    headers = {"User-Agent": "TitanOS-Plugins upstream check"}
    if url.startswith("https://api.github.com/") and os.environ.get("GH_TOKEN"):
        headers["Authorization"] = "Bearer " + os.environ["GH_TOKEN"]
    with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=120) as response:
        data = response.read(limit + 1)
    if len(data) > limit:
        raise ValueError(f"{url}: larger than expected")
    return data


def numbers(version):
    return tuple(int(part) for part in version.split("."))


def sha256(data):
    return hashlib.sha256(data).hexdigest()


# Every plugin: where its newest release is read, the archive and its notices.
# "fixed" notices are the license of the program: they must not change.

def tailscale_latest():
    return json.loads(get("https://pkgs.tailscale.com/stable/?mode=json", 1 << 20))["TarballsVersion"]


def netbird_latest():
    release = json.loads(get("https://api.github.com/repos/netbirdio/netbird/releases/latest", 1 << 20))
    if release.get("prerelease") or release.get("draft"):
        raise ValueError("NetBird's latest release is a pre-release")
    return release["tag_name"].removeprefix("v")


PLUGINS = {
    "tailscale": {
        "latest": tailscale_latest,
        "url": "https://pkgs.tailscale.com/stable/tailscale_{v}_amd64.tgz",
        # The publisher's own checksum of that archive.
        "checksums": "https://pkgs.tailscale.com/stable/tailscale_{v}_amd64.tgz.sha256",
        "source": "https://github.com/tailscale/tailscale/tree/v{v}",
        "notices": [
            ("LICENSE", "https://raw.githubusercontent.com/tailscale/tailscale/v{v}/LICENSE", "fixed"),
            ("third-party.html", "https://tailscale.com/licenses/tailscale", "list"),
        ],
    },
    "netbird": {
        "latest": netbird_latest,
        "url": "https://github.com/netbirdio/netbird/releases/download/v{v}/netbird_{v}_linux_amd64.tar.gz",
        "checksums": "https://github.com/netbirdio/netbird/releases/download/v{v}/netbird_{v}_checksums.txt",
        "source": "https://github.com/netbirdio/netbird/tree/v{v}",
        "notices": [
            ("LICENSE", "https://raw.githubusercontent.com/netbirdio/netbird/v{v}/LICENSE", "fixed"),
            ("BSD-3-Clause.txt", "https://raw.githubusercontent.com/netbirdio/netbird/v{v}/LICENSES/BSD-3-Clause.txt", "fixed"),
            ("third-party.txt", "generated by scripts/netbird-notices.py from the binary above", "generated"),
        ],
    },
}


def lock_path(name):
    return REPO / "plugins" / name / "packages.lock.json"


def check():
    newer = []
    for name, plugin in PLUGINS.items():
        pinned = json.loads(lock_path(name).read_text())["version"]
        latest = plugin["latest"]()
        if not VERSION.fullmatch(latest):
            raise ValueError(f"{name}: odd upstream version {latest!r}")
        if numbers(latest) > numbers(pinned):
            print(f"{name}={latest}")
            newer.append(name)
    print("names=" + " ".join(newer))


class LicenseChanged(Exception):
    pass


def bump(name, version):
    if name not in PLUGINS or not VERSION.fullmatch(version):
        raise SystemExit("usage: upstream.py bump <tailscale|netbird> <version>")
    plugin = PLUGINS[name]
    lock = json.loads(lock_path(name).read_text())
    if numbers(version) <= numbers(lock["version"]):
        raise SystemExit(f"{name} {version} is not newer than {lock['version']}")
    url = plugin["url"].format(v=version)
    archive = get(url)
    # What gets pinned here is built into a plugin and may be signed without
    # anyone looking: it has to be the archive the publisher names, not
    # whatever this one download returned (a cut-off or swapped file).
    published = get(plugin["checksums"].format(v=version), 1 << 20).decode("ascii", "replace")
    if sha256(archive) not in re.findall(r"\b[0-9a-f]{64}\b", published):
        raise SystemExit(f"{name} {version}: the archive does not match the publisher's checksum")
    licenses = REPO / "plugins" / name / "licenses"
    texts, notices = {}, []
    for file, notice_url, kind in plugin["notices"]:
        if kind == "generated":
            continue
        data = get(notice_url.format(v=version), 16 << 20)
        if kind == "fixed" and data != (licenses / file).read_bytes():
            raise LicenseChanged(f"{name} {version}: {file} differs from the pinned text")
        texts[file] = data
    if name == "netbird":
        with tempfile.TemporaryDirectory() as work, tarfile.open(fileobj=io.BytesIO(archive)) as tar:
            binary = Path(work) / "netbird"
            binary.write_bytes(tar.extractfile(tar.getmember("netbird")).read())
            output = Path(work) / "third-party.txt"
            subprocess.run([sys.executable, str(REPO / "scripts/netbird-notices.py"), str(binary), str(output)], check=True)
            texts["third-party.txt"] = output.read_bytes()
    for file, notice_url, kind in plugin["notices"]:
        (licenses / file).write_bytes(texts[file])
        notices.append({"file": file, "url": notice_url.format(v=version), "sha256": sha256(texts[file])})
    lock.update(version=version, url=url, sha256=sha256(archive), size=len(archive),
                source=plugin["source"].format(v=version), notices=notices)
    lock_path(name).write_text(json.dumps(lock, indent=2) + "\n")
    print(f"{name} {version} pinned ({len(archive)} bytes)")


def main(args):
    if args == ["check"]:
        check()
    elif len(args) == 3 and args[0] == "bump":
        try:
            bump(args[1], args[2])
        except LicenseChanged as error:
            print(error, file=sys.stderr)
            sys.exit(3)
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main(sys.argv[1:])
